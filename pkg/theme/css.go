// Pair is one contrast obligation, with the criterion that imposes it.
type Pair struct {
	What      string
	Fg, Bg    color.OKLCH
	Min       float64
	Criterion string
}

// Ratio is the measured contrast of the pair.
func (p Pair) Ratio() float64 { return color.Contrast(p.Fg, p.Bg) }

// Passes reports whether the pair meets its threshold.
func (p Pair) Passes() bool { return p.Ratio() >= p.Min }

// SeriesPairs holds each chart series against the page. A series colour is the
// whole encoding of a line or a wedge, so one that sinks into the background
// takes its data with it.
func (s Scheme) SeriesPairs() []Pair {
	out := make([]Pair, 0, SeriesCount)
	for i, c := range s.Series {
		out = append(out, Pair{
			What:      "chart series " + string(rune('a'+i)),
			Fg:        c,
			Bg:        s.Paper,
			Min:       color.AANonText,
			Criterion: "1.4.11",
		})
	}
	return out
}

// sortedNames is a stable name list for diffing two token maps.
func sortedNames(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// Diff reports token values present in a but different in b, as "name: a → b"
// lines. It backs the test that re-derives the palette and compares it with what
// the stylesheet actually says.
func Diff(a, b map[string]string) []string {
	var out []string
	for _, name := range sortedNames(a) {
		if got, ok := b[name]; !ok {
			out = append(out, name+": missing")
		} else if got != a[name] {
			out = append(out, fmt.Sprintf("%s: %s → %s", name, a[name], got))
		}
	}
	return out
}
